'use client';

import React, { useState } from 'react';
import { ForecastData, MLPredictionData, CitySearchResult } from '../types/weather';

interface OrbActionsDockProps {
  city: CitySearchResult;
  forecast: ForecastData | null;
  mlPrediction: MLPredictionData | null;
  onNavigateTab: (tab: string) => void;
  orientation?: 'horizontal' | 'vertical';
}

export default function OrbActionsDock({
  city,
  forecast,
  mlPrediction,
  onNavigateTab,
  orientation = 'horizontal'
}: OrbActionsDockProps) {
  const [toastMessage, setToastMessage] = useState<string | null>(null);

  const showToast = (msg: string) => {
    setToastMessage(msg);
    setTimeout(() => {
      setToastMessage(null);
    }, 3200);
  };

  // Action 1: Ask AI / Create Query
  const handleAskAI = () => {
    onNavigateTab('chat');
  };

  // Action 2: Export / Copy Telemetry Report
  const handleExportTelemetry = () => {
    if (!forecast) {
      showToast('Forecast telemetry pending');
      return;
    }

    const report = `WEATHERGPT METEOROLOGICAL TELEMETRY REPORT
Location: ${city.name}, ${city.country} (${city.latitude.toFixed(2)}°, ${city.longitude.toFixed(2)}°)
Timestamp: ${new Date().toISOString()}

[OBSERVED TELEMETRY]
• Temperature: ${forecast.current.temperature}°C (Feels like: ${forecast.current.feelsLike}°C)
• Condition: ${forecast.current.condition}
• Relative Humidity: ${forecast.current.humidity}%
• Surface Wind: ${forecast.current.windSpeed} km/h
• Atmospheric Pressure: ${forecast.current.pressure} hPa

[CUSTOM MACHINE LEARNING INFERENCE]
• Next-Day Mean Temp: ${mlPrediction?.temperature_prediction ? `${mlPrediction.temperature_prediction.predicted_temp_celsius}°C (R² = 0.9750)` : 'N/A'}
• Next-Day Rain Probability: ${mlPrediction?.rainfall_prediction ? `${mlPrediction.rainfall_prediction.rain_probability_pct}% (${mlPrediction.rainfall_prediction.will_rain ? 'Rain Expected' : 'Dry Day Expected'})` : 'N/A'}

Generated by WeatherGPT (Lovely Professional University)`;

    if (navigator.clipboard) {
      navigator.clipboard.writeText(report).then(() => {
        showToast('Telemetry Report copied to clipboard');
      }).catch(() => {
        showToast('Report generated successfully');
      });
    } else {
      showToast('Report generated successfully');
    }
  };

  // Action 3: Confirm / Live Radar or Model Verification
  const handleRadarOrConfirm = () => {
    onNavigateTab('map');
  };

  return (
    <div className="relative flex flex-col items-center">
      {/* Toast Notification */}
      {toastMessage && (
        <div className="absolute -top-12 z-50 px-4 py-2 rounded-2xl bg-slate-950/95 border border-cyan-400/40 text-cyan-300 text-xs font-bold shadow-2xl backdrop-blur-2xl animate-in fade-in slide-in-from-bottom-2 duration-200 whitespace-nowrap">
          {toastMessage}
        </div>
      )}

      {/* Button Stack Component */}
      <div className={`button-stack ${orientation === 'vertical' ? 'stack-vertical' : ''}`}>
        
        {/* Orb 1: Create / Ask Gemini AI (btn-teal) */}
        <div className="btn-wrapper">
          <button
            onClick={handleAskAI}
            className="orb-btn btn-teal"
            aria-label="Ask AI Assistant"
            title="Ask Gemini AI"
          >
            <svg viewBox="0 0 24 24" aria-hidden="true">
              <line x1="12" y1="4" x2="12" y2="20"></line>
              <line x1="4" y1="12" x2="20" y2="12"></line>
            </svg>
          </button>
          <span className="btn-label">Ask AI</span>
        </div>

        {/* Orb 2: Export / Share Report (btn-silver) */}
        <div className="btn-wrapper">
          <button
            onClick={handleExportTelemetry}
            className="orb-btn btn-silver"
            aria-label="Export Telemetry Report"
            title="Export Report"
          >
            <svg viewBox="0 0 24 24" aria-hidden="true">
              <path d="M7 17 L17 7 M17 7 L9 7 M17 7 L17 15"></path>
            </svg>
          </button>
          <span className="btn-label">Export</span>
        </div>

        {/* Orb 3: Confirm / Open Live Radar (btn-mauve) */}
        <div className="btn-wrapper">
          <button
            onClick={handleRadarOrConfirm}
            className="orb-btn btn-mauve"
            aria-label="Launch Satellite Radar"
            title="Live Radar"
          >
            <svg viewBox="0 0 24 24" aria-hidden="true">
              <path d="M5 13 L10 17.5 L19 7"></path>
            </svg>
          </button>
          <span className="btn-label">Radar</span>
        </div>

      </div>
    </div>
  );
}
